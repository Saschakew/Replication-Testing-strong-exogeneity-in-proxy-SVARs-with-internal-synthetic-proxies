function [oilTests, monetaryTests, moments] = run_replication()
%RUN_REPLICATION Reproduce the two application tables.
%   Table 1 is the oil application (Section 6.1), Table 2 the monetary
%   application (Section 6.2). 
%   Place the three files listed in data/README.md in data/ and run this
%   function. It writes the two LaTeX tables and proxy_moments.csv in output/.

root = fileparts(mfilename('fullpath'));
dataDir = fullfile(root, 'data');
outputDir = fullfile(root, 'output');
requiredInputs = {'dataBaseM.mat', 'OilSurprisesMLog.mat', 'data.csv'};
for i = 1:numel(requiredInputs)
    if ~isfile(fullfile(dataDir, requiredInputs{i}))
        error('run_replication:MissingData', ...
            'Missing data/%s. Follow the instructions in data/README.md.', requiredInputs{i});
    end
end

originalPath = path;
restorePath = onCleanup(@() path(originalPath));
addpath(fullfile(root, 'applications'), fullfile(root, 'functions'), '-begin');

fprintf('Running the Kaenzig oil supply news application ...\n');
[oilTests, oilProxy, oilDates] = application_kaenzig(dataDir);
fprintf('Running the Jarocinski-Karadi monetary policy application ...\n');
[monetaryTests, monetaryProxy, monetaryDates] = application_jk(dataDir);

moments = [summarizeProxy("Kaenzig", oilProxy, oilDates); ...
    summarizeProxy("Jarocinski-Karadi", monetaryProxy, monetaryDates)];
if ~isfolder(outputDir)
    mkdir(outputDir);
end
writeTestTable(fullfile(outputDir, 'tab_kaenzig_exogeneity_tests.tex'), ...
    oilTests, 'application_kaenzig.m');
writeTestTable(fullfile(outputDir, 'tab_jk_exogeneity_tests.tex'), ...
    monetaryTests, 'application_jk.m');
writetable(moments, fullfile(outputDir, 'proxy_moments.csv'));
fprintf('Wrote both tables and proxy_moments.csv to %s\n', outputDir);
end

function summary = summarizeProxy(application, proxy, dates)
% The paragraphs discussing Table 1 and Table 2 give skewness and excess
% kurtosis of the external proxy. To reproduce those descriptive numbers,
% use nonzero surprises. The tests themselves use every residual month.
nonzero = proxy(proxy ~= 0);
summary = table(application, string(dates(1), 'yyyy-MM'), string(dates(end), 'yyyy-MM'), ...
    numel(proxy), numel(nonzero), skewness(nonzero), kurtosis(nonzero) - 3, ...
    'VariableNames', {'Application', 'FirstMonth', 'LastMonth', 'Months', ...
    'NonzeroMonths', 'Skewness', 'ExcessKurtosis'});
end

function writeTestTable(tableFile, results, generatorName)
% Round the statistics and probabilities to the precision printed in the paper.

fid = fopen(tableFile, 'w');
if fid < 0
    error('run_replication:TableOutput', ...
        'Could not open table file for writing: %s', tableFile);
end
cleanup = onCleanup(@() fclose(fid));

fprintf(fid, '%% Auto-generated by %s\n', generatorName);
fprintf(fid, '\\begin{tabular}{llcc}\n');
fprintf(fid, '\\toprule\n');
fprintf(fid, 'Test & Version & Statistic & $p$-value \\\\\n');
fprintf(fid, '\\midrule\n');
for i = 1:height(results)
    fprintf(fid, '%s & %s & %.2f & %.3f \\\\\n', ...
        results.test{i}, results.version{i}, results.statistic(i), results.p_value(i));
end
fprintf(fid, '\\bottomrule\n');
fprintf(fid, '\\end{tabular}\n');
end
